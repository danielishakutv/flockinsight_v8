/**
 * English — the source of truth.
 *
 * `Dictionary` is derived from this object, and every other locale is typed as
 * `Dictionary`. So a missing key, a stray key, or a string where a plural pair
 * belongs is a TYPE ERROR, not something a user discovers. That is the whole
 * reason the dictionaries are TypeScript and not JSON: `pnpm exec tsc --noEmit`
 * is the completeness check, and it runs before every commit.
 *
 * Rules for adding a key:
 *   - It must be a string somebody actually sees. Nothing here is for logs,
 *     comments or developer messages.
 *   - Write it the way a person would say it. These are read by pastors and
 *     church secretaries, not by engineers.
 *   - `{name}` style placeholders. Keep them few and obvious — a translator
 *     cannot reorder what they cannot see.
 *   - A count gives a `{ one, other }` pair. `Intl.PluralRules` picks the form,
 *     so languages with different rules than English still read correctly.
 */

