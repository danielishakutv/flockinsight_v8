/**
 * The shape every other locale must match, exactly.
 *
 * `typeof en` rather than a hand-written interface: the English file is the
 * only place a key is ever added, and every translator's file fails to compile
 * until it catches up. That is the completeness guarantee.
 *
 * Deliberately NOT `as const`. With literal types every other locale would be
 * required to repeat the English words, which is the opposite of the point;
 * widened to `string`, what is enforced is the SHAPE — every key present, and a
 * `{ one, other }` pair wherever English has one.
 */
export type Dictionary = typeof en;
